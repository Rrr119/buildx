package buildflags

import (
	"fmt"
	"slices"
)

// SPDX SBOM and in-toto provenance attestation predicate types.
const (
	// PredicateSPDX is the in-toto predicate type for SPDX documents.
	PredicateSPDX = "https://spdx.dev/Document"
	// PredicateSLSAProvenance is the in-toto predicate type for SLSA
	// provenance statements emitted by BuildKit.
	PredicateSLSAProvenance = "https://slsa.dev/provenance/v1"
)

// Attestation types supported by the BuildKit frontend.
const (
	AttestationTypeSBOM       = "sbom"
	AttestationTypeProvenance = "provenance"
)

// DefaultSBOMGenerator is the BuildKit-provided SBOM generator. It runs
// syft and emits SPDX JSON documents, one per platform image.
const DefaultSBOMGenerator = "docker/buildkit-syft-scanner:stable-1"

// SecurityAttestations returns the attestation entries that make up the
// default secure software supply chain preset: an SPDX SBOM and an in-toto
// provenance statement, both attached per platform.
//
// User-provided attestations take precedence so that custom generators or
// provenance modes are never silently overwritten.
func SecurityAttestations(userAttests Attests) (Attests, error) {
	out := slices.Clone(userAttests)
	have := map[string]bool{}
	for _, a := range out {
		have[a.Type] = true
	}

	if !have[AttestationTypeSBOM] {
		var att Attest
		if err := att.UnmarshalText([]byte(SBOMAttestation(DefaultSBOMGenerator))); err != nil {
			return nil, err
		}
		out = append(out, &att)
	}

	if !have[AttestationTypeProvenance] {
		var att Attest
		if err := att.UnmarshalText([]byte(ProvenanceAttestation("max"))); err != nil {
			return nil, err
		}
		out = append(out, &att)
	}

	return out.Normalize(), nil
}

// SBOMAttestation returns the canonical CSV attestation string for an SPDX
// SBOM generated by the given generator image. An empty generator selects the
// BuildKit default SPDX generator.
func SBOMAttestation(generator string) string {
	if generator == "" {
		generator = DefaultSBOMGenerator
	}
	return fmt.Sprintf("type=%s,generator=%s", AttestationTypeSBOM, generator)
}

// ProvenanceAttestation returns the canonical CSV attestation string for an
// in-toto SLSA provenance statement. mode is typically "min" or "max".
func ProvenanceAttestation(mode string) string {
	if mode == "" {
		mode = "max"
	}
	return fmt.Sprintf("type=%s,mode=%s", AttestationTypeProvenance, mode)
}
